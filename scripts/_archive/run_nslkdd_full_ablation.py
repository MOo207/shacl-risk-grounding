JSON_FENCE = re.compile(r'```json\s*\n?(.*?)```', re.DOTALL)


def _parse_response(text: str) -> Optional[dict]:
    m = JSON_FENCE.search(text)
    blob = m.group(1) if m else text
    try:
        return json.loads(blob)
    except Exception:
        f, l = blob.find('{'), blob.rfind('}')
        if f >= 0 and l > f:
            try:
                return json.loads(blob[f:l+1])
            except Exception:
                return None
    return None


def _fmt_cve(cve: Optional[dict]) -> str:
    if not cve:
        return 'No CVE context.'
    return (f"CVE: {cve.get('id')}  CVSS: {cve.get('cvss_v3')}  "
            f"Desc: {cve.get('shortDescription', '')[:120]}")


def run_llm_paradigm(cases: list[dict], paradigm: str, model: str,
                     out_path: Path, start_offset: int = 0,
                     client: Any = None) -> None:
    if client is None:
        from scripts.claude_cli_client import ClaudeCLIClient
        client = ClaudeCLIClient(model=model, max_tokens=600, timeout_sec=180)

    cases_to_run = cases[start_offset:]
    mode = 'a' if start_offset > 0 else 'w'
    print(f'  Model: {model} | Cases: {len(cases_to_run)} | offset={start_offset}')

    with out_path.open(mode, encoding='utf-8') as fh:
        for i, case in enumerate(cases_to_run, start_offset + 1):
            t0      = time.time()
            cid     = case['case_id']
            crit    = case['criticality']
            gt      = case['ground_truth_risk_level']
            cve     = case.get('paired_cve')
            asset_j = json.dumps(case.get('asset', {}))
            cve_blk = _fmt_cve(cve)
            nl_desc = case.get('nl_description', '')

            # SHACL pre-filter for tri-stage paradigms
            shacl_ok = True
            if 'tristage' in paradigm:
                shacl_ok, _ = shacl_validate(case)

            if not shacl_ok:
                risk_lvl = 'Very Low'
                correct  = risk_lvl == gt
                record = {
                    'case_id': cid, 'paradigm': paradigm, 'model': model,
                    'true_class': case['true_attack_class'],
                    'risk_level': risk_lvl, 'ground_truth': gt,
                    'correct': correct, 'parse_error': False,
                    'shacl_filtered': True, 'criticality': crit,
                    'grc': 'Full', 'narrative': '', 'control': '',
                    'latency_ms': 0, 'timestamp': time.strftime('%Y-%m-%dT%H:%M:%S'),
                }
                fh.write(json.dumps(record, ensure_ascii=False) + '\n')
                fh.flush()
                match = 'OK' if correct else 'MISS'
                print(f'  [{i}/{len(cases)}] {cid}: SHACL_FILTERED → Very Low vs GT={gt} [{match}]')
                continue

            if 'tristage_llm' in paradigm:
                ml_cls  = case['xgb_predicted_class']
                ml_conf = case.get('xgb_confidence', 1.0)
                prompt = PROMPT_TRISTAGE.format(
                    attack_class=ml_cls,
                    confidence=f"{ml_conf:.0%}",
                    criticality=crit,
                    asset_json=asset_j, cve_block=cve_blk,
                    nl_desc=nl_desc[:1000],
                )
                system = SYSTEM_TRISTAGE
            else:
                prompt = PROMPT_PURE.format(
                    criticality=crit, asset_json=asset_j,
                    cve_block=cve_blk, nl_desc=nl_desc[:1000],
                )
                system = SYSTEM_PURE_LLM

            try:
                response = client.generate(system, prompt) or ''
            except Exception:
                response = ''

            artifact = _parse_response(response)
            latency  = int((time.time() - t0) * 1000)

            if artifact:
                risk_lvl = artifact.get('risk_level', '')
                # For tri-stage: if LLM overrode the ML class, recompute risk level
                # from the verified class to ensure §6.9 consistency
                if 'tristage_llm' in paradigm:
                    verified_cls = artifact.get('verified_attack_class', '')
                    if verified_cls and verified_cls in NSLKDD_TO_NFCRM:
                        nfcrm_verified = NSLKDD_TO_NFCRM[verified_cls]
                        risk_lvl = risk_lookup(nfcrm_verified, crit)
                correct  = risk_lvl == gt
                parse_ok = True
                verified_cls = artifact.get('verified_attack_class', '')
            else:
                risk_lvl, correct, parse_ok, verified_cls = '', False, False, ''

            record = {
                'case_id':          cid,
                'paradigm':         paradigm,
                'model':            model,
                'true_class':       case['true_attack_class'],
                'true_nfcrm':       case.get('true_nfcrm_class', ''),
                'ml_pred':          case.get('xgb_predicted_class', ''),
                'llm_verified_cls': verified_cls,
                'risk_level':       risk_lvl,
                'ground_truth':     gt,
                'correct':          correct,
                'parse_error':      not parse_ok,
                'shacl_filtered':   False,
                'criticality':      crit,
                'grc':              'Full',
                'narrative':        (artifact or {}).get('narrative', ''),
                'control':          (artifact or {}).get('recommended_control_id', ''),
                'latency_ms':       latency,
                'timestamp':        time.strftime('%Y-%m-%dT%H:%M:%S'),
            }
            fh.write(json.dumps(record, ensure_ascii=False) + '\n')
            fh.flush()
            match = 'OK' if correct else 'MISS'
            print(f'  [{i}/{len(cases)}] {cid}: {risk_lvl or "PARSE_ERR"} vs GT={gt} [{match}] ({latency}ms)')


