# ── CMDB loader ───────────────────────────────────────────────────────────────

def load_cmdb(cmdb_path: Path) -> dict[str, dict]:
    """Return {asset_id: asset_dict} from cmdb_assets.json."""
    raw = json.loads(cmdb_path.read_text())
    return {a['asset_id']: a for a in raw['assets']}


def pick_asset(true_cls: str, service: str, cmdb: dict[str, dict], rng: random.Random) -> dict:
    """Pick the most relevant CMDB asset for this flow, falling back gracefully."""
    # Try service-specific first, then attack-type based
    candidates = (
        SERVICE_ASSET_MAP.get(service.lower(), []) +
        ATTACK_ASSET_PREF.get(true_cls, [])
    )
    for aid in candidates:
        if aid in cmdb:
            return cmdb[aid]
    # Fallback: random asset from the 33
    return rng.choice(list(cmdb.values()))


def extract_cve_from_asset(asset: dict, nfcrm_class: str, rng: random.Random) -> Optional[dict]:
    """Extract a relevant CVE from the matched CMDB asset's software list."""
    all_cves = []
    for sw in asset.get('software', []):
        for cve in sw.get('cves', []):
            all_cves.append({
                'id':               cve['cve_id'],
                'cvss_v3':          cve.get('cvss', 'N/A'),
                'shortDescription': cve.get('description', ''),
                'software':         sw.get('name', ''),
            })
    if not all_cves:
        return None
    return rng.choice(all_cves)


# ── NSL-KDD raw loading ───────────────────────────────────────────────────────

def load_raw(filepath: Path) -> pd.DataFrame:
    df = pd.read_csv(filepath, names=COLUMN_NAMES, header=None)
    df['label'] = df['label'].str.strip().str.rstrip('.').str.lower()
    df['label'] = df['label'].map(ATTACK_MAPPING).fillna('Normal')
    if 'difficulty' in df.columns:
        df = df.drop('difficulty', axis=1)
    df = df[df['label'].isin(CLASSES)].reset_index(drop=True)
    return df


def encode_for_ml(train_raw: pd.DataFrame, test_raw: pd.DataFrame):
    """One-hot encode jointly so train/test share the same feature space."""
    CAT_COLS = ['protocol_type', 'service', 'flag']
    combined = pd.concat(
        [train_raw.assign(_split='train'), test_raw.assign(_split='test')],
        ignore_index=True,
    )
    enc = pd.get_dummies(combined, columns=CAT_COLS, drop_first=False)
    feat_cols = [c for c in enc.columns if c not in ('label', '_split')]
    enc[feat_cols] = enc[feat_cols].apply(pd.to_numeric, errors='coerce').fillna(0)
    train_enc = enc[enc['_split'] == 'train'].drop('_split', axis=1).reset_index(drop=True)
    test_enc  = enc[enc['_split'] == 'test'].drop('_split', axis=1).reset_index(drop=True)
    return train_enc, test_enc, feat_cols


def train_ml_models(train_enc: pd.DataFrame, feat_cols: list[str]):
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.preprocessing import LabelEncoder

    X  = train_enc[feat_cols].values.astype(float)
    le = LabelEncoder()
    y  = le.fit_transform(train_enc['label'].values)

    # class_weight='balanced' compensates for extreme NSL-KDD imbalance
    # (R2L=0.8%, U2R=0.04% of KDDTrain+) — without this, RF/XGB never predict rare classes
    print('Training RF on KDDTrain+ (class_weight=balanced) ...')
    rf = RandomForestClassifier(n_estimators=200, random_state=42, n_jobs=-1,
                                class_weight='balanced')
    rf.fit(X, y)
    print(f'  RF classes: {le.classes_}')

    try:
        from xgboost import XGBClassifier
        from sklearn.utils.class_weight import compute_sample_weight
        sample_w = compute_sample_weight('balanced', y)
        print('Training XGBoost (sample_weight=balanced) ...')
        xgb = XGBClassifier(n_estimators=200, random_state=42,
                            eval_metric='mlogloss', use_label_encoder=False, verbosity=0)
        xgb.fit(X, y, sample_weight=sample_w)
        print('  XGBoost done.')
    except ImportError:
        print('  XGBoost unavailable — using RF as fallback')
        xgb = rf

    return rf, xgb, le


# ── SHACL pre-filter (ontology validation, no Neo4j required) ─────────────────

def shacl_validate(case: dict) -> tuple[bool, str]:
    """
    Lightweight SHACL-equivalent ontology validation for NSL-KDD flows.
    Returns (passes, reason). Mirrors NFCRM-1:2025 §5 monitoring constraints.
    """
    f = case.get('feature_subset', {})
    protocol   = str(f.get('protocol_type', '')).lower()
    flag       = str(f.get('flag', '')).upper()
    src_bytes  = int(f.get('src_bytes', -1))
    dst_bytes  = int(f.get('dst_bytes', -1))
    duration   = float(f.get('duration', -1))

    # Constraint 1: protocol must be known
    if protocol not in VALID_PROTOCOLS:
        return False, f'unknown protocol: {protocol}'

    # Constraint 2: flag must be a recognised TCP state flag
    if flag and flag not in VALID_FLAGS:
        return False, f'unrecognised flag: {flag}'

    # Constraint 3: byte counts must be non-negative
    if src_bytes < 0 or dst_bytes < 0:
        return False, f'negative byte count: src={src_bytes}, dst={dst_bytes}'

    # Constraint 4: duration must be non-negative
    if duration < 0:
        return False, f'negative duration: {duration}'

    return True, 'OK'


# ── §6.9 risk level ───────────────────────────────────────────────────────────

def risk_lookup(nfcrm_class: str, criticality: str) -> str:
    from pipeline.nfcrm.risk_score import compute_risk_score
    c_val = CRIT_MAP.get(criticality, 3)
    score = compute_risk_score(nfcrm_class, c_override=c_val, i_override=c_val, a_override=c_val)
    return 'Very Low' if score.level_en == 'N/A (non-attack)' else score.level_en


# ── Symbolic rule ─────────────────────────────────────────────────────────────

def symbolic_rule_predict(case: dict) -> str:
    """Signature-based NSL-KDD class prediction from feature_subset."""
    f = case.get('feature_subset', {})
    protocol   = str(f.get('protocol_type', 'tcp')).lower()
    service    = str(f.get('service', 'other')).lower()
    flag       = str(f.get('flag', 'SF')).upper()
    duration   = float(f.get('duration', 0))
    src_bytes  = int(f.get('src_bytes', 0))
    dst_bytes  = int(f.get('dst_bytes', 0))
    count      = int(f.get('count', 0))
    diff_srv   = float(f.get('diff_srv_rate', 0.0))
    dst_h_cnt  = int(f.get('dst_host_count', 0))
    root_shell = int(f.get('root_shell', 0))
    su_att     = int(f.get('su_attempted', 0))
    num_root   = int(f.get('num_root', 0))
    num_shells = int(f.get('num_shells', 0))
    num_failed = int(f.get('num_failed_logins', 0))
    wrong_frag = int(f.get('wrong_fragment', 0))

    if root_shell or su_att or num_root > 0 or num_shells > 0:
        return 'U2R'
    if num_failed > 0:
        return 'R2L'
    if service in ('ftp', 'ftp_data') and duration >= 200:
        return 'R2L'
    if protocol == 'udp' and service == 'private' and dst_bytes == 0 and src_bytes < 200:
        return 'R2L'
    if diff_srv >= 0.5:
        return 'Probe'
    if protocol == 'icmp' and src_bytes <= 28:
        return 'Probe'
    if wrong_frag > 0:
        return 'DoS'
    if flag in ('REJ', 'S0') and count >= 50 and diff_srv < 0.4:
        return 'DoS'
    if service == 'http' and src_bytes >= 10000 and dst_h_cnt >= 200 and diff_srv < 0.2:
        return 'DoS'
    return 'Normal'


# ── Test set builder ──────────────────────────────────────────────────────────

def build_test_set(seed: int = 42, n_per_class: int = 10) -> dict:
    from run_slm_nslkdd_classification import features_to_nl_nslkdd

    rng = random.Random(seed)
    np.random.seed(seed)

    train_path = ROOT / 'data' / 'raw' / 'NSL-KDD' / 'KDDTrain+.txt'
    test_path  = ROOT / 'data' / 'raw' / 'NSL-KDD' / 'KDDTest+.txt'
    cmdb_path  = ROOT / 'data' / 'external' / 'cmdb_assets.json'

    print('Loading NSL-KDD raw files ...')
    train_raw = load_raw(train_path)
    test_raw  = load_raw(test_path)
    print(f'  KDDTrain+: {len(train_raw):,} rows  |  KDDTest+: {len(test_raw):,} rows')

    for cls in CLASSES:
        n = (test_raw['label'] == cls).sum()
        if n < n_per_class:
            raise ValueError(f"Class '{cls}' has {n} rows in KDDTest+ — need {n_per_class}.")

    print('Encoding for ML ...')
    train_enc, test_enc, feat_cols = encode_for_ml(train_raw, test_raw)

    rf_model, xgb_model, le = train_ml_models(train_enc, feat_cols)

    # Stratified sample 10/class from KDDTest+
    eval_idxs: list[int] = []
    for cls in CLASSES:
        cls_idxs = test_raw.index[test_raw['label'] == cls].tolist()
        rng_s = random.Random(seed)
        eval_idxs.extend(rng_s.sample(cls_idxs, n_per_class))

    eval_raw = test_raw.loc[eval_idxs].copy()
    eval_enc = test_enc.loc[eval_idxs].copy()
    # Shuffle
    shuffled_idxs = list(eval_idxs)
    random.Random(seed).shuffle(shuffled_idxs)
    eval_raw = test_raw.loc[shuffled_idxs].reset_index(drop=True)
    eval_enc = test_enc.loc[shuffled_idxs].reset_index(drop=True)

    X_eval    = eval_enc[feat_cols].values.astype(float)
    rf_preds  = le.inverse_transform(rf_model.predict(X_eval))
    xgb_preds = le.inverse_transform(xgb_model.predict(X_eval))
    rf_proba  = rf_model.predict_proba(X_eval).max(axis=1)
    xgb_proba = xgb_model.predict_proba(X_eval).max(axis=1)

    cmdb = load_cmdb(cmdb_path)
    print(f'Loaded {len(cmdb)} CMDB assets.')

    cases = []
    for i, (_, row) in enumerate(eval_raw.iterrows()):
        true_cls    = row['label']
        nfcrm_cls   = NSLKDD_TO_NFCRM[true_cls]
        service     = str(row.get('service', 'other')).lower()

        asset_rec   = pick_asset(true_cls, service, cmdb, rng)
        criticality = asset_rec['criticality'].capitalize()
        if criticality not in CRIT_MAP:
            criticality = rng.choice(CRITICALITIES)
        c_val = CRIT_MAP[criticality]

        paired_cve  = extract_cve_from_asset(asset_rec, nfcrm_cls, rng)

        gt_risk     = risk_lookup(nfcrm_cls, criticality)

        rf_cls       = rf_preds[i]
        nfcrm_rf     = NSLKDD_TO_NFCRM.get(rf_cls, 'Benign')
        rf_risk      = risk_lookup(nfcrm_rf, criticality)

        xgb_cls      = xgb_preds[i]
        nfcrm_xgb    = NSLKDD_TO_NFCRM.get(xgb_cls, 'Benign')
        xgb_risk     = risk_lookup(nfcrm_xgb, criticality)

        nl_desc = features_to_nl_nslkdd(row)

        feature_subset = {
            'protocol_type':  str(row.get('protocol_type', 'tcp')),
            'service':         str(row.get('service', 'other')),
            'flag':            str(row.get('flag', 'SF')),
            'duration':        float(row.get('duration', 0)),
            'src_bytes':       int(row.get('src_bytes', 0)),
            'dst_bytes':       int(row.get('dst_bytes', 0)),
            'count':           int(row.get('count', 0)),
            'diff_srv_rate':   float(row.get('diff_srv_rate', 0.0)),
            'dst_host_count':  int(row.get('dst_host_count', 0)),
            'root_shell':      int(row.get('root_shell', 0)),
            'su_attempted':    int(row.get('su_attempted', 0)),
            'num_root':        int(row.get('num_root', 0)),
            'num_shells':      int(row.get('num_shells', 0)),
            'num_failed_logins': int(row.get('num_failed_logins', 0)),
            'wrong_fragment':  int(row.get('wrong_fragment', 0)),
        }

        asset_info = {
            'id':          asset_rec['asset_id'],
            'hostname':    asset_rec['hostname'],
            'ip':          asset_rec.get('ip', ''),
            'port':        asset_rec.get('port', 0),
            'os':          asset_rec.get('os', ''),
            'criticality': criticality,
            'asset_type':  asset_rec.get('asset_type', 'server'),
            'software':    [sw.get('name') for sw in asset_rec.get('software', [])],
        }

        cases.append({
            'case_id':                 f'nsl_{i:03d}',
            'dataset':                 'NSL-KDD',
            'true_attack_class':       true_cls,
            'true_nfcrm_class':        nfcrm_cls,
            'asset':                   asset_info,
            'paired_cve':              paired_cve,
            'nl_description':          nl_desc,
            'feature_subset':          feature_subset,
            'rf_predicted_class':      rf_cls,
            'rf_nfcrm_class':          nfcrm_rf,
            'rf_confidence':           float(rf_proba[i]),
            'rf_risk_level':           rf_risk,
            'xgb_predicted_class':     xgb_cls,
            'xgb_nfcrm_class':         nfcrm_xgb,
            'xgb_confidence':          float(xgb_proba[i]),
            'xgb_risk_level':          xgb_risk,
            'ground_truth_risk_level': gt_risk,
            'criticality':             criticality,
        })

    rf_acc  = sum(1 for c in cases if c['rf_risk_level']  == c['ground_truth_risk_level']) / len(cases)
    xgb_acc = sum(1 for c in cases if c['xgb_risk_level'] == c['ground_truth_risk_level']) / len(cases)
    cls_dist = {cls: sum(1 for c in cases if c['true_attack_class'] == cls) for cls in CLASSES}
    print(f'  Class distribution: {cls_dist}')
    print(f'  ML risk-level accuracy — RF: {rf_acc:.1%}  XGB: {xgb_acc:.1%}')
    print(f'  Asset match example: {cases[0]["asset"]["id"]} ({cases[0]["asset"]["hostname"]}) '
          f'crit={cases[0]["criticality"]}')

    return {
        'meta': {
            'description': 'NSL-KDD Unified Ablation — real CMDB assets, all paradigms, N=50 (10/class)',
            'dataset': 'NSL-KDD',
            'n': len(cases),
            'n_per_class': n_per_class,
            'seed': seed,
            'classes': CLASSES,
            'nfcrm_mapping': NSLKDD_TO_NFCRM,
            'rf_risk_accuracy': rf_acc,
            'xgb_risk_accuracy': xgb_acc,
            'class_distribution': cls_dist,
            'cmdb_source': 'data/external/cmdb_assets.json',
            'train_source': 'data/raw/NSL-KDD/KDDTrain+.txt',
            'eval_source':  'data/raw/NSL-KDD/KDDTest+.txt',
            'created': datetime.now().isoformat(),
        },
        'cases': cases,
    }


# ── Non-LLM paradigm runner ───────────────────────────────────────────────────

def run_nonllm(cases: list[dict], paradigm: str) -> list[dict]:
    results = []
    for case in cases:
        cid      = case['case_id']
        crit     = case['criticality']
        gt       = case['ground_truth_risk_level']
        true_cls = case['true_attack_class']

        if paradigm == 'rule':
            pred_nsl = symbolic_rule_predict(case)
            nfcrm_cl = NSLKDD_TO_NFCRM.get(pred_nsl, 'Benign')
            risk     = risk_lookup(nfcrm_cl, crit)
            grc      = 'None'
            pred_cls = pred_nsl
            shacl_ok = True

        elif paradigm == 'shacl_only':
            passes, reason = shacl_validate(case)
            if passes:
                pred_nsl = symbolic_rule_predict(case)
                nfcrm_cl = NSLKDD_TO_NFCRM.get(pred_nsl, 'Benign')
                risk     = risk_lookup(nfcrm_cl, crit)
                pred_cls = pred_nsl
            else:
                risk     = 'Very Low'
                pred_cls = 'Normal'
            grc      = 'None'
            shacl_ok = passes

        elif paradigm == 'ml_rf':
            pred_cls = case['rf_predicted_class']
            risk     = case['rf_risk_level']
            grc      = 'None'
            shacl_ok = True

        elif paradigm == 'ml_xgb':
            pred_cls = case['xgb_predicted_class']
            risk     = case['xgb_risk_level']
            grc      = 'None'
            shacl_ok = True

        elif paradigm == 'tristage_rf':
            passes, _ = shacl_validate(case)
            shacl_ok  = passes
            if passes:
                pred_cls = case['rf_predicted_class']
                risk     = case['rf_risk_level']
            else:
                pred_cls = 'Normal'
                risk     = 'Very Low'
            grc = 'Partial'

        elif paradigm == 'tristage_xgb':
            passes, _ = shacl_validate(case)
            shacl_ok  = passes
            if passes:
                pred_cls = case['xgb_predicted_class']
                risk     = case['xgb_risk_level']
            else:
                pred_cls = 'Normal'
                risk     = 'Very Low'
            grc = 'Partial'

        else:
            raise ValueError(f'Unknown paradigm: {paradigm}')

        results.append({
            'case_id':      cid,
            'paradigm':     paradigm,
            'true_class':   true_cls,
            'pred_class':   pred_cls,
            'risk_level':   risk,
            'ground_truth': gt,
            'correct':      risk == gt,
            'grc':          grc,
            'shacl_pass':   shacl_ok,
            'criticality':  crit,
        })

    correct = sum(1 for r in results if r['correct'])
    print(f'  {paradigm}: {correct}/{len(results)} = {correct/len(results):.1%}')
    return results


