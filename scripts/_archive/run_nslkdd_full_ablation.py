NON_LLM = ['rule', 'shacl_only', 'ml_rf', 'ml_xgb', 'tristage_rf', 'tristage_xgb']
LLM_PAR = ['pure_llm', 'tristage_llm_haiku', 'tristage_llm_sonnet']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--paradigm', nargs='+', choices=NON_LLM + LLM_PAR)
    ap.add_argument('--all-nonllm', action='store_true',
                    help='Run all non-LLM paradigms (default when no --paradigm given)')
    ap.add_argument('--llm', action='store_true', help='Also run LLM paradigms after non-LLM')
    ap.add_argument('--summary', action='store_true')
    ap.add_argument('--rebuild', action='store_true', help='Force rebuild test set')
    ap.add_argument('--test-set', default='results/nslkdd_ablation/test_set.json')
    ap.add_argument('--out-dir',  default='results/nslkdd_ablation')
    ap.add_argument('--model', default=None)
    ap.add_argument('--start-offset', type=int, default=0)
    ap.add_argument('--seed', type=int, default=42)
    ap.add_argument('--n-per-class', type=int, default=10)
    args = ap.parse_args()

    out_dir = ROOT / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.summary:
        print_summary(out_dir)
        return

    # ── Build or load test set ──────────────────────────────────────────────
    ts_path = ROOT / args.test_set
    if args.rebuild or not ts_path.exists():
        print('Building NSL-KDD test set with real CMDB assets ...')
        ts = build_test_set(seed=args.seed, n_per_class=args.n_per_class)
        ts_path.parent.mkdir(parents=True, exist_ok=True)
        ts_path.write_text(json.dumps(ts, indent=2, ensure_ascii=False), encoding='utf-8')
        print(f'Saved {ts["meta"]["n"]} cases to {ts_path}\n')
    else:
        print(f'Loading existing test set from {ts_path}')

    all_cases = json.loads(ts_path.read_text())['cases']
    print(f'  {len(all_cases)} cases | classes: '
          + str({cls: sum(1 for c in all_cases if c["true_attack_class"] == cls)
                 for cls in CLASSES}))

    # ── Determine what to run ───────────────────────────────────────────────
    to_run: list[str] = list(args.paradigm or [])
    if not to_run or args.all_nonllm:
        to_run = list(NON_LLM) if args.all_nonllm or not to_run else to_run
    if args.llm and not args.paradigm:
        to_run = list(NON_LLM) + list(LLM_PAR)

    for paradigm in to_run:
        out_path = out_dir / f'{paradigm}.jsonl'
        print(f'\n--- {paradigm} ---')

        if paradigm in NON_LLM:
            results = run_nonllm(all_cases, paradigm)
            mode = 'a' if args.start_offset > 0 else 'w'
            with out_path.open(mode, encoding='utf-8') as fh:
                for r in results[args.start_offset:]:
                    fh.write(json.dumps(r, ensure_ascii=False) + '\n')
        else:
            if args.model:
                model = args.model
            elif 'haiku' in paradigm:
                model = 'claude-haiku-4-5-20251001'
            else:
                model = 'claude-sonnet-4-6'
            run_llm_paradigm(all_cases, paradigm, model, out_path, args.start_offset)

    if to_run:
        print_summary(out_dir)


if __name__ == '__main__':
    main()
