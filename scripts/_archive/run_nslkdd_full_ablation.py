def analyze_jsonl(path: Path) -> dict:
    if not path.exists():
        return {}
    lines = []
    for l in path.read_text(errors='replace').splitlines():
        l = l.strip()
        if not l:
            continue
        try:
            lines.append(json.loads(l))
        except json.JSONDecodeError:
            pass
    n = len(lines)
    correct = sum(1 for l in lines if l.get('correct'))
    parse_errs = sum(1 for l in lines if l.get('parse_error'))
    grc = lines[0].get('grc', '?') if lines else '?'
    shacl_filtered = sum(1 for l in lines if l.get('shacl_filtered'))
    return {'n': n, 'accuracy': correct / n if n else 0,
            'grc': grc, 'parse_errors': parse_errs, 'shacl_filtered': shacl_filtered}


