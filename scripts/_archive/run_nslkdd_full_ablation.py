def print_summary(out_dir: Path) -> None:
    print(f"\n{'Paradigm':<27} {'Accuracy':>10} {'GRC':>8} {'N':>5} "
          f"{'SHACLfil':>9} {'ParseErr':>9}")
    print('-' * 72)
    for p in PARADIGM_ORDER:
        r = analyze_jsonl(out_dir / f'{p}.jsonl')
        if r:
            print(f"  {p:<25} {r['accuracy']:>9.1%} {r['grc']:>8} {r['n']:>5} "
                  f"{r['shacl_filtered']:>8} {r['parse_errors']:>9}")
        else:
            print(f"  {p:<25} {'—':>9}  {'—':>8}")


